    "<7I",
    0x2C8200A0,  # sltiu v0, a0, 0xA0 (a0 is the base weapon ID)
    0x10400003,  # beq v0, zero, return
    0x3C030000 | (RAC3INSTRUCTION.MEGA_PURCHASE_FLAGS >> 16),  # lui v1, flag table high half
